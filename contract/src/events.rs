//! NEP-297 events, one log line per state change:
//! `EVENT_JSON:{"standard":"agent_guard","version":"1.0.0","event":"<name>","data":[{...}]}`.

use near_sdk::json_types::U128;
use near_sdk::serde::Serialize;
use near_sdk::{AccountId, near};

use crate::types::{DenyReason, TransferStatus};

#[derive(Serialize)]
#[serde(crate = "near_sdk::serde")]
pub(crate) struct PolicySetData<'a> {
    pub agent: &'a AccountId,
    pub per_tx_max: U128,
    pub window_limit: U128,
    pub window_secs: u64,
    pub allowed_receivers: &'a [AccountId],
}

#[derive(Serialize)]
#[serde(crate = "near_sdk::serde")]
pub(crate) struct AgentRevokedData<'a> {
    pub agent: &'a AccountId,
}

/// Payload of both `spend_approved` (empty `reasons`) and `spend_denied`.
#[derive(Serialize)]
#[serde(crate = "near_sdk::serde")]
pub(crate) struct SpendData<'a> {
    pub index: u64,
    pub agent: &'a AccountId,
    pub receiver: &'a AccountId,
    pub amount: U128,
    pub attempt_id: &'a str,
    pub reasons: &'a [DenyReason],
}

#[derive(Serialize)]
#[serde(crate = "near_sdk::serde")]
pub(crate) struct TransferSettledData<'a> {
    pub index: u64,
    pub agent: &'a AccountId,
    pub receiver: &'a AccountId,
    pub amount: U128,
    pub transfer: TransferStatus,
    /// yoctoNEAR taken back off the agent's window spend: non-zero only for a failed transfer
    /// charged to the window that is still current.
    pub window_refund: U128,
}

#[derive(Serialize)]
#[serde(crate = "near_sdk::serde")]
pub(crate) struct OwnerWithdrawData {
    pub amount: U128,
}

/// `emit()` (generated by near-sdk) writes the `EVENT_JSON:` log line; the event name is the
/// variant name in snake_case.
#[near(event_json(standard = "agent_guard"))]
pub(crate) enum GuardEvent<'a> {
    #[event_version("1.0.0")]
    PolicySet(&'a [PolicySetData<'a>]),
    #[event_version("1.0.0")]
    AgentRevoked(&'a [AgentRevokedData<'a>]),
    #[event_version("1.0.0")]
    SpendApproved(&'a [SpendData<'a>]),
    #[event_version("1.0.0")]
    SpendDenied(&'a [SpendData<'a>]),
    #[event_version("1.0.0")]
    TransferSettled(&'a [TransferSettledData<'a>]),
    #[event_version("1.0.0")]
    OwnerWithdraw(&'a [OwnerWithdrawData]),
}
